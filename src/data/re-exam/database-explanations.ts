export function explainDatabase(question: Question, index: number): string | undefined {
  if (index < fourthFormExplanations.length) return fourthFormExplanations[index];
  if (question.type !== 'text') return undefined;
  const answer = Array.isArray(question.answer) ? question.answer[0] : question.answer;
  if (question.question.startsWith('各列は単一値')) {
    const relation = question.question.split('\n')[1];
    const reason: Record<string, string> = {
      '第1正規形': '複合候補キーの一部から非キー列が決まる部分関数従属があるため、第2正規形を満たさない。',
      '第2正規形': '部分関数従属はないが、キーから非キー列を経て別の非キー列が決まるため、第3正規形を満たさない。',
      '第3正規形': 'スーパーキーでない決定項が候補キーの構成属性を決める。第3正規形の条件は満たすがボイスコッドの正規形の条件は満たさない。',
      'ボイスコッドの正規形': '記載された非自明な関数従属の決定項はいずれもスーパーキーなので、問題文の判別対象の中ではボイスコッドの正規形まで満たす。',
      '第4正規形': '記載された関数従属とそこから導かれる多値従属はいずれも、非自明な場合は決定項がスーパーキーである。ほかの非自明な多値従属はないという条件から、第4正規形を満たす。',
    };
    return `${relation}\n${reason[answer] ?? ''}`;
  }
  if (question.question.includes('\n') && question.question.includes('候補キーは')) {
    if (byAnswer[answer]) return byAnswer[answer];
    return `示された関数従属を左辺から右辺へ読む。${answer}に対応する矢印と候補キーを比較すると、この列が条件に当てはまる。`;
  }
  return byAnswer[answer];
}
